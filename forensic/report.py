import os
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle

def create_pdf_report(record, output_dir):
    os.makedirs(output_dir, exist_ok=True)
    output_path = os.path.join(output_dir, f"forensic-report-{record['id']}.pdf")
    doc = SimpleDocTemplate(output_path, pagesize=A4, rightMargin=18*mm, leftMargin=18*mm)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name="SmallWrap", parent=styles["BodyText"], fontSize=8, leading=11, wordWrap="CJK"))
    analysis = record.get("analysis", {})
    file_info = analysis.get("file_info", {})
    story = [
        Paragraph("Digital Forensics Analyzer", styles["Title"]),
        Paragraph("Digital Evidence Analysis Report", styles["Heading2"]),
        Spacer(1, 8),
        Paragraph("Scope: This report records basic file properties and cryptographic hashes. It does not establish authenticity, authorship, or criminal activity.", styles["SmallWrap"]),
        Spacer(1, 12)
    ]
    rows = [
        ["Evidence ID", str(record["id"])],
        ["Case reference", record.get("case_ref") or "Not provided"],
        ["Original filename", record["original_name"]],
        ["MIME type", record.get("file_type") or "Unknown"],
        ["File size", file_info.get("size_readable", str(record.get("file_size", "")))],
        ["File modified (UTC)", record.get("created_at") or "Unknown"],
        ["MD5", record.get("md5") or ""],
        ["SHA-256", record.get("sha256") or ""],
        ["Investigator notes", record.get("notes") or "None"]
    ]
    table = Table(rows, colWidths=[42*mm, 130*mm])
    table.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (0,-1), colors.HexColor("#e9eef5")),
        ("GRID", (0,0), (-1,-1), 0.4, colors.HexColor("#ccd4df")),
        ("VALIGN", (0,0), (-1,-1), "TOP"),
        ("FONTNAME", (0,0), (0,-1), "Helvetica-Bold"),
        ("FONTSIZE", (0,0), (-1,-1), 8),
        ("WORDWRAP", (0,0), (-1,-1), "CJK"),
        ("LEFTPADDING", (0,0), (-1,-1), 7),
        ("RIGHTPADDING", (0,0), (-1,-1), 7),
        ("TOPPADDING", (0,0), (-1,-1), 7),
        ("BOTTOMPADDING", (0,0), (-1,-1), 7),
    ]))
    story.extend([table, Spacer(1, 14), Paragraph("Interpretation and limitations", styles["Heading3"]),
        Paragraph("A matching SHA-256 hash can help demonstrate that two copies have identical contents. A hash alone does not prove where a file came from or whether it was altered before collection. File timestamps and metadata may be changed or unreliable. Preserve original evidence and document chain of custody separately.", styles["SmallWrap"]),
        Spacer(1, 10), Paragraph("Generated by Digital Forensics Analyzer (educational prototype).", styles["Italic"])])
    doc.build(story)
    return output_path
